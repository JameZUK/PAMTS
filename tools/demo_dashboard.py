def sparse_tree(base):
    """A library with realistic file SIZES and no disk cost.

    The tier scan measures st_size, so a sparse file reports its full length while
    occupying nothing -- which is what lets a 350G library live in a tmpdir.
    """
    import random
    random.seed(11)
    def mk(path, n):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.truncate(n)
    for s in ("Documentary Series", "Comedy Series", "Drama Series", "Nature Series"):
        for ep in range(1, 9):
            mk(os.path.join(base, "tv", s, "S0%dE%02d.mkv" % (1 + ep % 3, ep)),
               int((6.4 + random.random() * 2.2) * G))
    for f in ("Film (2016)", "Another Film (2019)", "Third Film (2021)",
              "Fourth Film (2012)", "Fifth Film (2018)", "Sixth Film (2004)",
              "Seventh Film (2023)", "Eighth Film (1998)", "Ninth Film (2010)",
              "Tenth Film (2015)"):
        mk(os.path.join(base, "movies", f, f + " WEBDL-1080p.mkv"),
           int((7.1 + random.random() * 3.0) * G))
    for a in ("Artist One", "Artist Two", "Artist Three", "Artist Four", "Artist Five"):
        for al in range(1, 9):
            for tr in range(1, 13):
                mk(os.path.join(base, "music", a, "Album %d" % al, "%02d Track.flac" % tr),
                   int((38 + random.random() * 26) * M))


