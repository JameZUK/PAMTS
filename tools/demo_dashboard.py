def serve(port, handler):
    t = threading.Thread(target=ThreadingHTTPServer(("127.0.0.1", port), handler)
                         .serve_forever, daemon=True)
    t.start()


def json_handler(route):
    class H(BaseHTTPRequestHandler):
        def do_GET(self):
            body = json.dumps(route(self.path)).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers(); self.wfile.write(body)
        def log_message(self, *a): pass
    return H


def front_handler():
    class H(BaseHTTPRequestHandler):
        def do_GET(self):
            if self.path.startswith("/api/health"):
                body = json.dumps({
                    "overall": "ok", "generated": time.time(),
                    "counts": {"ok": len(CHECKS), "warn": 0, "fail": 0},
                    "checks": [{"group": g, "name": n, "state": "ok", "detail": d}
                               for g, n, d in CHECKS]}).encode()
                ctype, status = "application/json", 200
            else:
                try:
                    with urllib.request.urlopen(
                            f"http://127.0.0.1:{WEB_PORT}{self.path}", timeout=10) as r:
                        body = r.read()
                        ctype = r.headers.get("Content-Type", "text/html")
                        status = r.status
                except Exception as e:                           # noqa: BLE001
                    body, ctype, status = str(e).encode(), "text/plain", 502
            self.send_response(status)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers(); self.wfile.write(body)
        def log_message(self, *a): pass
    return H


