    build(ROOT)
    serve(OBS_PORT, json_handler(
        lambda p: {"sessions": LIVE} if p.startswith("/sessions")
        else STATS if p.startswith("/stats") else {"ok": True}))
    web = subprocess.Popen([sys.executable, str(HERE / "pamts-web.py"),
                            "--config", str(ROOT / "pamts.toml"),
                            "--observer-url", f"http://127.0.0.1:{OBS_PORT}",
                            "--observer-db", str(ROOT / "observer.db"),
                            "--state-file", str(ROOT / "state.json"),
                            "--events-db", str(ROOT / "events.db"),
                            "--listen", f"127.0.0.1:{WEB_PORT}",
                            "--sources", "observer,state,config,events,history,tier"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(3)
    serve(FRONT_PORT, front_handler())
    print(f"demo dashboard on http://127.0.0.1:{FRONT_PORT}/  (ctrl-c to stop)",
          file=sys.stderr)
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        pass
    finally:
        web.terminate()
    return 0


